#!/usr/bin/env node
/*
 * Regenerates the two derived data files from data/trip.js:
 *
 *   data/routes.js   road geometry + distance/duration for every leg and loop (OSRM)
 *   data/gallery.js  lead photos of each stop's `wiki` articles (Wikipedia/Commons),
 *                    downloaded into images/<stop-id>/
 *
 * Everything is cached: only legs whose waypoints changed and wiki titles not yet
 * downloaded are fetched. Usage:
 *
 *   node tools/build.mjs            # update what changed
 *   node tools/build.mjs routes     # only routes
 *   node tools/build.mjs images     # only images
 *   node tools/build.mjs --force    # refetch everything
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const FORCE = args.includes("--force");
const ONLY = args.find((a) => !a.startsWith("--"));
const UA = "coast-to-coast-trip-planner/1.0 (personal itinerary; node fetch)";
const OSRM = "https://router.project-osrm.org/route/v1/driving/";

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function loadWindowFile(file, key) {
  const p = path.join(ROOT, file);
  if (!fs.existsSync(p)) return null;
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(p, "utf8"), ctx, { filename: p });
  return ctx.window[key] ?? null;
}

function writeWindowFile(file, key, value, comment) {
  const body = `// ${comment}\n// GENERATED by tools/build.mjs — do not edit by hand.\nwindow.${key} = ${JSON.stringify(value)};\n`;
  fs.writeFileSync(path.join(ROOT, file), body);
}

// Must match routeKey() in app.js — used to detect stale cached geometry.
const routeKey = (pts) => pts.map((p) => `${(+p[0]).toFixed(4)},${(+p[1]).toFixed(4)}`).join(";");

// ── Route legs ──────────────────────────────────────────────────────────────

function collectLegs(trip) {
  const legs = [];
  trip.stops.forEach((stop, i) => {
    if (stop.ride && i > 0) {
      const pts = [trip.stops[i - 1].coords, ...(stop.ride.via || []), stop.coords];
      legs.push({ id: stop.id, pts });
    }
    (stop.explore || []).forEach((ex, k) => {
      if (ex.loop && ex.loop.length) legs.push({ id: `${stop.id}#${k}`, pts: [stop.coords, ...ex.loop, stop.coords] });
    });
  });
  return legs;
}

// Ramer–Douglas–Peucker, keeps file size sane without visibly changing the line.
function simplify(points, tol) {
  if (points.length < 3) return points;
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = points[a], [bx, by] = points[b];
    const dx = bx - ax, dy = by - ay, len2 = dx * dx + dy * dy || 1e-12;
    let maxD = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const [px, py] = points[i];
      const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / len2));
      const ex = ax + t * dx - px, ey = ay + t * dy - py;
      const d = ex * ex + ey * ey;
      if (d > maxD) (maxD = d), (idx = i);
    }
    if (maxD > tol * tol && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

async function fetchRoute(pts) {
  const coords = pts.map((p) => `${p[1]},${p[0]}`).join(";");
  const url = `${OSRM}${coords}?overview=full&geometries=geojson&continue_straight=false`;
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    if (res.ok) {
      const json = await res.json();
      if (json.code === "Ok") {
        const r = json.routes[0];
        const line = r.geometry.coordinates.map(([lon, lat]) => [+lat.toFixed(5), +lon.toFixed(5)]);
        return { distance: Math.round(r.distance), duration: Math.round(r.duration), coords: simplify(line, 0.0004) };
      }
      throw new Error(`OSRM: ${json.code} ${json.message || ""}`);
    }
    await sleep(2000 * (attempt + 1));
  }
  throw new Error("OSRM request failed");
}

async function buildRoutes(trip) {
  const cache = (!FORCE && loadWindowFile("data/routes.js", "ROUTES")) || {};
  const out = {};
  const legs = collectLegs(trip);
  let fetched = 0;
  for (const leg of legs) {
    const key = routeKey(leg.pts);
    if (cache[leg.id] && cache[leg.id].key === key) {
      out[leg.id] = cache[leg.id];
      continue;
    }
    process.stdout.write(`route ${leg.id} … `);
    try {
      const r = await fetchRoute(leg.pts);
      out[leg.id] = { key, ...r };
      fetched++;
      console.log(`${(r.distance / 1609.34).toFixed(0)} mi, ${(r.duration / 3600).toFixed(1)} h`);
    } catch (e) {
      console.log(`FAILED (${e.message}) — page will draw a straight line`);
    }
    await sleep(1100);
  }
  writeWindowFile("data/routes.js", "ROUTES", out, "Road geometry per leg (key = stop id, or stopId#exploreIndex for loops).");
  console.log(`routes: ${legs.length} legs, ${fetched} fetched`);
}

// ── Images ─────────────────────────────────────────────────────────────────

const SKIP_FILE = /\.(svg|gif|tif?f)$|map|locator|shield|logo|seal|flag|coat_of_arms|signature|diagram/i;
const stripHtml = (s = "") => s.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);

async function fetchRetry(url) {
  for (let attempt = 0; attempt < 6; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA, "Api-User-Agent": UA } });
    if (res.status !== 429 && res.status < 500) return res;
    const wait = (+res.headers.get("retry-after") || 2 ** attempt * 2) * 1000;
    process.stdout.write(`(${res.status}, waiting ${wait / 1000}s) `);
    await sleep(wait);
  }
  throw new Error(`gave up: ${url}`);
}
const API = "https://en.wikipedia.org/w/api.php?format=json&formatversion=2&action=query&";

// Batched: article title -> { file, description, page }. 50 titles per request.
async function lookupArticles(titles) {
  const out = {};
  for (let i = 0; i < titles.length; i += 50) {
    const batch = titles.slice(i, i + 50);
    const url = API + "redirects=1&prop=pageimages|description|info&inprop=url&piprop=name&titles=" + encodeURIComponent(batch.join("|"));
    const json = await (await fetchRetry(url)).json();
    const alias = {};
    for (const n of json.query.normalized || []) alias[n.to] = n.from;
    for (const r of json.query.redirects || []) alias[r.to] = alias[r.from] || r.from;
    for (const p of json.query.pages) {
      const original = alias[p.title] || p.title;
      const key = batch.find((t) => t.replace(/_/g, " ") === original || t === original) || original;
      out[key] = { title: p.title, file: p.pageimage, description: p.description, page: p.fullurl, missing: p.missing };
    }
    await sleep(500);
  }
  return out;
}

// Batched: file name -> { url (960px), credit, source }.
async function lookupFiles(files) {
  const out = {};
  for (let i = 0; i < files.length; i += 50) {
    const batch = files.slice(i, i + 50);
    const url = API + "prop=imageinfo&iiprop=url|extmetadata&iiurlwidth=960&titles=" + encodeURIComponent(batch.map((f) => "File:" + f).join("|"));
    const json = await (await fetchRetry(url)).json();
    for (const p of json.query.pages) {
      const ii = p.imageinfo?.[0];
      if (!ii) continue;
      const meta = ii.extmetadata || {};
      out[p.title.replace(/^File:/, "").replace(/ /g, "_")] = {
        url: ii.thumburl || ii.url,
        credit: [stripHtml(meta.Artist?.value), meta.LicenseShortName?.value].filter(Boolean).join(" · "),
        source: ii.descriptionurl,
      };
    }
    await sleep(500);
  }
  return out;
}

async function buildImages(trip) {
  const cache = (!FORCE && loadWindowFile("data/gallery.js", "GALLERY")) || {};
  const out = {};
  const todo = [];
  for (const stop of trip.stops) {
    out[stop.id] = [];
    for (const title of stop.wiki || []) {
      const cached = (cache[stop.id] || []).find((g) => g.wiki === title);
      if (cached && fs.existsSync(path.join(ROOT, cached.src))) out[stop.id].push(cached);
      else todo.push({ stop, title });
    }
  }
  const articles = todo.length ? await lookupArticles([...new Set(todo.map((t) => t.title))]) : {};
  const fileNames = [...new Set(Object.values(articles).map((a) => a.file).filter((f) => f && !SKIP_FILE.test(f)))];
  const files = fileNames.length ? await lookupFiles(fileNames) : {};

  let fetched = 0;
  for (const { stop, title } of todo) {
    process.stdout.write(`image ${stop.id} / ${title} … `);
    const a = articles[title];
    if (!a || a.missing) { console.log("skipped: article not found"); continue; }
    if (!a.file) { console.log("skipped: no lead image"); continue; }
    if (SKIP_FILE.test(a.file)) { console.log(`skipped: looks like a map/logo (${a.file})`); continue; }
    const f = files[a.file];
    if (!f) { console.log("skipped: no image info"); continue; }
    try {
      const ext = (path.extname(new URL(f.url).pathname) || ".jpg").toLowerCase();
      const rel = `images/${stop.id}/${slug(title)}${ext}`;
      fs.mkdirSync(path.join(ROOT, "images", stop.id), { recursive: true });
      const res = await fetchRetry(f.url);
      if (!res.ok) throw new Error(`download ${res.status}`);
      fs.writeFileSync(path.join(ROOT, rel), Buffer.from(await res.arrayBuffer()));
      // Keep the order of stop.wiki
      out[stop.id].push({ wiki: title, src: rel, caption: a.title, description: a.description || "", credit: f.credit, source: f.source, page: a.page });
      fetched++;
      console.log("ok");
    } catch (e) {
      console.log(`FAILED (${e.message})`);
    }
    await sleep(400);
  }
  for (const stop of trip.stops) {
    const order = stop.wiki || [];
    out[stop.id].sort((x, y) => order.indexOf(x.wiki) - order.indexOf(y.wiki));
  }
  writeWindowFile("data/gallery.js", "GALLERY", out, "Photos per stop, from the `wiki` titles in trip.js. Credits from Wikimedia Commons.");
  console.log(`images: ${fetched} downloaded`);
}

// ── main ───────────────────────────────────────────────────────────────────

const trip = loadWindowFile("data/trip.js", "TRIP");
if (!trip) throw new Error("data/trip.js did not define window.TRIP");
const ids = new Set();
for (const s of trip.stops) {
  if (ids.has(s.id)) throw new Error(`duplicate stop id: ${s.id}`);
  ids.add(s.id);
}
if (!ONLY || ONLY === "routes") await buildRoutes(trip);
if (!ONLY || ONLY === "images") await buildImages(trip);
